"""Apply the small schema migration needed by the local employee API."""

import psycopg

from config import DB_HOST, DB_NAME, DB_PASSWORD, DB_PORT, DB_USER


def migrate():
    with psycopg.connect(
        host=DB_HOST,
        port=DB_PORT,
        dbname=DB_NAME,
        user=DB_USER,
        password=DB_PASSWORD,
    ) as connection:
        column = connection.execute(
            """
            SELECT is_identity
            FROM information_schema.columns
            WHERE table_schema = 'public'
              AND table_name = 'employees'
              AND column_name = 'id'
            """
        ).fetchone()

        if column is None:
            raise RuntimeError(
                "The employees table is missing. Initialize db/init/01_schema.sql first."
            )

        if column[0] == "NO":
            connection.execute(
                "ALTER TABLE employees ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY"
            )

        connection.execute(
            """
            SELECT setval(
                pg_get_serial_sequence('public.employees', 'id'),
                (SELECT MAX(id) FROM employees)
            )
            """
        )


if __name__ == "__main__":
    migrate()
